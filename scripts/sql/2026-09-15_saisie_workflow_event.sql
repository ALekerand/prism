-- Journal d’étapes du workflow de saisie (miroir V17).
CREATE TABLE IF NOT EXISTS saisie_workflow_event (
	ID_SAISIE_WORKFLOW_EVENT INT NOT NULL AUTO_INCREMENT,
	ID_SAISIE_WORKFLOW INT NOT NULL,
	ACTION VARCHAR(40) NOT NULL,
	LIBELLE VARCHAR(120) NULL,
	ACTEUR VARCHAR(100) NULL,
	DATE_ETAPE DATETIME(6) NULL,
	DETAIL VARCHAR(2000) NULL,
	PRIMARY KEY (ID_SAISIE_WORKFLOW_EVENT),
	KEY IX_SAISIE_WF_EVENT_WF (ID_SAISIE_WORKFLOW),
	CONSTRAINT FK_SAISIE_WF_EVENT_WF FOREIGN KEY (ID_SAISIE_WORKFLOW)
		REFERENCES saisie_workflow (ID_SAISIE_WORKFLOW)
		ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
